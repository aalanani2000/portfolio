import type { NextConfig } from "next";

// Content-Security-Policy analysis:
// - Fonts: self-hosted via next/font (no external font CDN)
// - Scripts: Next.js runtime + two small inline scripts (locale pre-hydration, JSON-LD)
//   → 'unsafe-inline' required for script-src; no user-controlled content reaches them
// - Styles: Tailwind injects <style> tags → 'unsafe-inline' required for style-src
// - Connect: browser only talks to same-origin /api/*; DeepSeek is called server-side
// - Images: local assets only
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const nextConfig: NextConfig = {
  turbopack: {
    root: __dirname,
  },
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=(), interest-cohort=()",
          },
          {
            key: "Strict-Transport-Security",
            value: "max-age=63072000; includeSubDomains; preload",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
